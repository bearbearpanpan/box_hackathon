"""
report.py — buildPdf() and createReviewTask(), the Report step from the pitch.

buildPdf renders the risk/research write-up into a PDF (reusing minipdf), ready
to upload back to Box. createReviewTask creates a review task for the deal desk
(via Box tasks when live, or a local JSON record in the offline fallback).
"""
from __future__ import annotations

import os
import sys
import json
from datetime import datetime
from typing import Dict, Any

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "data")))

from minipdf import PdfDoc  # type: ignore


def buildPdf(risk_report: Dict[str, Any], research: Dict[str, Any] | None = None) -> bytes:
    """Build the Reality Check report PDF and return its bytes."""
    doc = PdfDoc()
    r = risk_report
    doc.add_heading("REALITY CHECK — DEAL RISK REPORT")
    doc.add_paragraph(f"Draft: {r.get('draft_id')}    Generated: {datetime.utcnow().isoformat()}Z")
    doc.add_rule()

    doc.add_subheading(f"{r.get('overall_emoji','')} Overall risk: {r.get('overall_risk')}")
    doc.add_paragraph(r.get("headline", ""))

    if r.get("thin_history"):
        doc.add_paragraph("Note: thin history — fewer than 3 comparable deals were found.")

    doc.add_subheading("Comparable past deals")
    for c in r.get("comparables", []):
        doc.add_paragraph(
            f"- {c['contract_id']} ({c.get('customer','')}): promised {c.get('promised_days')}d, "
            f"actual {c.get('actual_days')}d  [{c.get('hw_vendor') or 'no-hw'}, "
            f"{c.get('region')}, {c.get('signed_quarter')}]"
        )

    st = r.get("suggested_timeline", {})
    doc.add_subheading("Suggested safer timeline")
    doc.add_keyvalue("Suggested delivery", f"{st.get('suggested_days')} days")
    if st.get("p50_actual") is not None:
        doc.add_keyvalue("Median actual (comparables)", f"{st.get('p50_actual')} days")
        doc.add_keyvalue("Worst case", f"{st.get('worst_actual')} days")

    doc.add_subheading("Risks & citations")
    for risk in r.get("risks", []):
        doc.add_paragraph(f"[{risk['severity']}] {risk['title']}")
        doc.add_paragraph(f"    {risk['detail']}")
        doc.add_paragraph(f"    Mitigation: {risk['mitigation']}")

    if research:
        doc.add_subheading("Deep research — features we could offer")
        for f in research.get("recommended_features", []):
            doc.add_paragraph(f"- {f['feature']} (fit {f['fit_score']}): {f['why']}")
        doc.add_spacer(4)
        doc.add_paragraph(research.get("research_brief", ""))

    doc.add_spacer(10)
    doc.add_rule()
    doc.add_paragraph("Generated by Reality Check. Synthetic demo data.")
    return doc.render()


def createReviewTask(source, report_file_id: str, draft_id: str, risk_level: str,
                     assignee: str = "deal-desk") -> Dict[str, Any]:
    """
    Create a review task for the deal desk on the uploaded report.
    `source` is a BoxClient (live) or LocalSource (offline).
    """
    message = f"Reality Check: review {draft_id} — risk {risk_level}. Confirm timeline before signature."

    # Live Box path: create a Box task on the file.
    if hasattr(source, "_connect"):
        try:
            task_id = source.create_review_task(report_file_id, message)
            return {"status": "created", "task_id": task_id, "assignee": assignee, "message": message}
        except Exception as exc:
            return {"status": "error", "error": str(exc), "message": message}

    # Offline fallback: write a task record next to the report.
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.abspath(os.path.join(here, "..", "..", "..", "data", "reports"))
    os.makedirs(out_dir, exist_ok=True)
    rec = {
        "status": "created_local",
        "report_file_id": report_file_id,
        "draft_id": draft_id,
        "risk_level": risk_level,
        "assignee": assignee,
        "message": message,
        "created_at": datetime.utcnow().isoformat() + "Z",
    }
    # draft_id is caller-derived; strip path components so the task record
    # can't be written outside the reports directory (path traversal).
    safe_draft_id = os.path.basename(str(draft_id)).replace("\\", "_") or "draft"
    task_path = os.path.join(out_dir, f"task_{safe_draft_id}.json")
    if os.path.commonpath([out_dir, os.path.abspath(task_path)]) != out_dir:
        raise ValueError(f"unsafe draft_id: {draft_id!r}")
    with open(task_path, "w") as fh:
        json.dump(rec, fh, indent=2)
    return rec
